#!/usr/bin/env bash
# Builds the game module, including modules that live in their own folders.
#
#   scripts/build.sh            # host module -> game/build/PolishedCrystal.so
#   scripts/build.sh --device   # also the .mote (needs the ARM toolchain)
#
# Why this wrapper exists: Mote's build tool compiles only the .c files at the
# top level of <game>/src (it does not recurse), so a module in a subfolder is
# silently missing and the link fails with "undefined symbol". Rather than
# forcing a flat src/ — the layout is chosen per system, not by a tool quirk —
# this script builds a throwaway flat mirror:
#
#   game/build/flat/src/...   copy of game/src (headers keep their paths)
#   game/build/flat/src/ow_map.c   one-line shim: #include "ow/map.c"
#
# so `mote build` sees a flat tree while the real sources stay organised. The
# shim approach keeps the official build (host and device) untouched, which
# matters because device packaging must go through it.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MOTE="$ROOT/vendor/mote/tools/mote"
export LD_LIBRARY_PATH="$ROOT/toolsrc/sdl-install/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
# The device build needs arm-none-eabi-*; setup.sh puts it in toolsrc/.
for d in "$ROOT"/toolsrc/arm-gnu-toolchain-*/bin; do
    [ -d "$d" ] && PATH="$d:$PATH"
done
export PATH

DEVICE=""
for arg in "$@"; do
    case "$arg" in
        --device) DEVICE="--device" ;;
        *) echo "usage: scripts/build.sh [--device]" >&2; exit 2 ;;
    esac
done

# Modules are .c files anywhere under src/, except the generated data and the
# per-module test files.
nested=$(find "$ROOT/game/src" -mindepth 2 -name '*.c' -not -path '*/gen/*' | head -1)

if [ -z "$nested" ]; then
    "$MOTE" build "$ROOT/game" $DEVICE
else
    FLAT="$ROOT/game/build/flat"
    rm -rf "$FLAT"
    mkdir -p "$FLAT"
    cp -r "$ROOT/game/src" "$FLAT/src"
    [ -f "$ROOT/game/cflags" ] && cp "$ROOT/game/cflags" "$FLAT/cflags"

    # One shim per nested source, named after its path (ow/map.c -> ow_map.c).
    while IFS= read -r f; do
        rel="${f#"$FLAT/src/"}"
        shim="$FLAT/src/$(printf '%s' "${rel%.c}" | tr '/' '_').c"
        printf '/* generated by scripts/build.sh — compiles %s */\n#include "%s"\n' \
            "$rel" "$rel" > "$shim"
    done < <(find "$FLAT/src" -mindepth 2 -name '*.c' -not -path '*/gen/*')

    "$MOTE" build "$FLAT" $DEVICE

    mkdir -p "$ROOT/game/build"
    cp "$FLAT/build/PolishedCrystal.so" "$ROOT/game/build/PolishedCrystal.so"
    if [ -n "$DEVICE" ] && [ -f "$FLAT/build/PolishedCrystal.mote" ]; then
        cp "$FLAT/build/PolishedCrystal.mote" "$ROOT/game/build/PolishedCrystal.mote"
    fi
    echo "built (mirrored): game/build/PolishedCrystal.so"
    if [ -n "$DEVICE" ]; then echo "built device: game/build/PolishedCrystal.mote"; fi
fi
